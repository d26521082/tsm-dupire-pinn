"""Aggregate all numeric results into a single results.tex for use by main.tex.

Reads:
  data/cv_summary.json           — LOMO + LOSO + AH + fold-bootstrap + paired tests
  data/sigma_analysis.json       — recovered surface stats and wing exponents
  data/sigma_sensitivity.json    — sigma_ref sensitivity (optional)
  data/sigma_robustness.json     — T-adaptive + window sensitivity + data bootstrap (optional)
  data/ablation_summary.json     — PDE-prior ablation (optional)
  data/baseline_metrics.json     — in-sample SVI / spline metrics
  data/american_premium.json     — early-exercise premium estimates (optional)
  data/clean.csv
Writes:
  results.tex
  highlights.txt
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
OUT = ROOT / "results.tex"


def fmt(x: float, places: int = 4) -> str:
    return f"{x:.{places}f}"


def load_json(name: str) -> dict | None:
    p = DATA / name
    if not p.exists():
        return None
    return json.loads(p.read_text())


def main() -> None:
    cv = load_json("cv_summary.json") or {}
    sig = load_json("sigma_analysis.json") or {}
    sigsens = load_json("sigma_sensitivity.json") or {}
    sigrob = load_json("sigma_robustness.json") or {}
    abl = load_json("ablation_summary.json") or {}
    bl = load_json("baseline_metrics.json") or {}
    amer = load_json("american_premium.json") or {}
    df = pd.read_csv(DATA / "clean.csv")

    n_clean = int(sig.get("n_data", len(df)))
    n_raw = 259
    q = float(sig.get("q", df.q_implied.iloc[0]))
    S = float(sig.get("S", df["S"].iloc[0]))
    r = float(sig.get("r", df["r"].iloc[0]))
    n_seeds = int(sig.get("n_seeds", 5))

    wings = sig.get("wing_exponents", [])
    aL = np.array([w["alpha_L"] for w in wings if not np.isnan(w["alpha_L"])])
    aR = np.array([w["alpha_R"] for w in wings if not np.isnan(w["alpha_R"])])
    R2L = np.array([w["R2_L"] for w in wings if not np.isnan(w["R2_L"])])
    R2R = np.array([w["R2_R"] for w in wings if not np.isnan(w["R2_R"])])

    sig_min = float(sig["sigma_loc_overall"]["mean_min"]) if sig else 0.0
    sig_max = float(sig["sigma_loc_overall"]["mean_max"]) if sig else 0.0
    sig_ens_max = float(sig["sigma_loc_overall"]["ensemble_std_max"]) if sig else 0.0
    skew_med = float(sig["leverage_skew"]["median"]) if sig else 0.0

    pinn = cv.get("models", {}).get("pinn", {})
    svi = cv.get("models", {}).get("svi", {})
    spline = cv.get("models", {}).get("spline", {})
    ah = cv.get("models", {}).get("ah", {})

    paired = {p["comparison"]: p for p in cv.get("paired_tests_fold_level", [])}

    def fmt_p(p: float) -> str:
        return r"<0.0001" if p < 1e-4 else f"{p:.4f}"

    L: list[str] = []
    L.append("% Auto-generated by analysis/build_results_tex.py — do not edit by hand")
    L.append("% Re-run that script to refresh numbers from data/*.json")
    L.append("")
    L.append("% ====== Data ======")
    L.append(rf"\newcommand{{\Nraw}}{{{n_raw}}}")
    L.append(rf"\newcommand{{\Nclean}}{{{n_clean}}}")
    L.append(rf"\newcommand{{\Nseeds}}{{{n_seeds}}}")
    L.append(rf"\newcommand{{\SpotPrice}}{{{fmt(S, 2)}}}")
    L.append(rf"\newcommand{{\RiskFree}}{{{fmt(r, 4)}}}")
    L.append(rf"\newcommand{{\ImpliedQ}}{{{fmt(q, 4)}}}")
    L.append(rf"\newcommand{{\ImpliedQPct}}{{{fmt(q * 100, 2)}}}")
    L.append("")

    if bl:
        L.append("% ====== In-sample (full N) ======")
        L.append(rf"\newcommand{{\SVIrmseIn}}{{{fmt(bl['svi']['rmse'])}}}")
        L.append(rf"\newcommand{{\SVImaeIn}}{{{fmt(bl['svi']['mae'])}}}")
        L.append(rf"\newcommand{{\SplineRmseIn}}{{{fmt(bl['spline']['rmse'])}}}")
        L.append("")

    if cv:
        L.append("% ====== LOMO out-of-sample (fold-bootstrap CI) ======")
        for tag, key in [("Pinn", "pinn"), ("SVI", "svi"), ("Spline", "spline"), ("AH", "ah")]:
            m = cv["models"].get(key, {})
            if not m: continue
            L.append(rf"\newcommand{{\{tag}RmseLOMO}}{{{fmt(m['rmse'])}}}")
            L.append(
                rf"\newcommand{{\{tag}RmseLOMOCI}}{{[{fmt(m['rmse_ci95'][0])},\ {fmt(m['rmse_ci95'][1])}]}}"
            )
            L.append(rf"\newcommand{{\{tag}MaeLOMO}}{{{fmt(m['mae'])}}}")
            L.append(rf"\newcommand{{\{tag}MaxErrLOMO}}{{{fmt(m['max_abs_err'], 2)}}}")
        L.append("")
        L.append("% ====== Fold-level paired tests (n_folds = 9) ======")
        for cmp_label, tag in [
            ("pinn vs svi", "PinnVsSVI"),
            ("pinn vs spline", "PinnVsSpline"),
            ("pinn vs ah", "PinnVsAH"),
            ("ah vs svi", "AHvsSVI"),
        ]:
            pt = paired.get(cmp_label)
            if not pt: continue
            L.append(rf"\newcommand{{\{tag}p}}{{{fmt_p(pt['p'])}}}")
            L.append(rf"\newcommand{{\{tag}t}}{{{fmt(pt['t'], 2)}}}")
        L.append("")

    if abl:
        L.append("% ====== PDE-prior ablation ======")
        for var_key, tag in [
            ("A_data_only", "AblA"),
            ("B_data_arb", "AblB"),
            ("C_data_pde", "AblC"),
            ("D_full", "AblD"),
        ]:
            v = abl.get(var_key, {})
            if not v: continue
            L.append(rf"\newcommand{{\{tag}InRmse}}{{{fmt(v['in_sample']['rmse'])}}}")
            L.append(rf"\newcommand{{\{tag}OosRmse}}{{{fmt(v['oos']['rmse'])}}}")
            L.append(rf"\newcommand{{\{tag}OosMae}}{{{fmt(v['oos']['mae'])}}}")
        L.append("")

    if sig:
        L.append("% ====== σ_loc surface ======")
        L.append(rf"\newcommand{{\SigmaLocMin}}{{{fmt(sig_min, 3)}}}")
        L.append(rf"\newcommand{{\SigmaLocMax}}{{{fmt(sig_max, 3)}}}")
        L.append(rf"\newcommand{{\SigmaEnsembleStdMax}}{{{fmt(sig_ens_max, 3)}}}")
        L.append(rf"\newcommand{{\LeverageSkewMedian}}{{{fmt(skew_med, 3)}}}")
        L.append("")
        if len(aL):
            L.append("% ====== Power-law wing exponents ======")
            L.append(rf"\newcommand{{\AlphaLmedian}}{{{fmt(float(np.median(aL)), 3)}}}")
            L.append(rf"\newcommand{{\AlphaLmin}}{{{fmt(float(aL.min()), 3)}}}")
            L.append(rf"\newcommand{{\AlphaLmax}}{{{fmt(float(aL.max()), 3)}}}")
            L.append(rf"\newcommand{{\AlphaLrsq}}{{{fmt(float(np.median(R2L)), 3)}}}")
            L.append(rf"\newcommand{{\AlphaRmedian}}{{{fmt(float(np.median(aR)), 3)}}}")
            L.append(rf"\newcommand{{\AlphaRmin}}{{{fmt(float(aR.min()), 3)}}}")
            L.append(rf"\newcommand{{\AlphaRmax}}{{{fmt(float(aR.max()), 3)}}}")
            L.append(rf"\newcommand{{\AlphaRrsq}}{{{fmt(float(np.median(R2R)), 3)}}}")
            L.append("")

    if amer:
        L.append("% ====== American early-exercise premium ======")
        for ot, tag in [("call", "AmerCall"), ("put", "AmerPut")]:
            m = amer.get("by_type", {}).get(ot, {})
            if not m: continue
            L.append(rf"\newcommand{{\{tag}MeanPrem}}{{{fmt(m['mean_premium'], 4)}}}")
            L.append(rf"\newcommand{{\{tag}MaxPrem}}{{{fmt(m['max_abs_premium'], 4)}}}")
        L.append("")

    if cv and ah:
        L.append("% ====== Comparison table (LOMO out-of-sample, all four models) ======")
        L.append(r"\newcommand{\LOMOtable}{%")
        L.append(r"\begin{tabular}{lccc}")
        L.append(r"\toprule")
        L.append(r"Model & RMSE (\$) & 95\% CI (fold-bootstrap) & MAE (\$) \\")
        L.append(r"\midrule")
        L.append(
            rf"\textbf{{PINN (Dupire)}} & \textbf{{{fmt(pinn['rmse'])}}} & "
            rf"$[{fmt(pinn['rmse_ci95'][0])},\ {fmt(pinn['rmse_ci95'][1])}]$ & "
            rf"\textbf{{{fmt(pinn['mae'])}}} \\"
        )
        L.append(
            rf"Andreasen--Huge & {fmt(ah['rmse'])} & "
            rf"$[{fmt(ah['rmse_ci95'][0])},\ {fmt(ah['rmse_ci95'][1])}]$ & "
            rf"{fmt(ah['mae'])} \\"
        )
        L.append(
            rf"SVI (slice + linear-$T$ interp.) & {fmt(svi['rmse'])} & "
            rf"$[{fmt(svi['rmse_ci95'][0])},\ {fmt(svi['rmse_ci95'][1])}]$ & "
            rf"{fmt(svi['mae'])} \\"
        )
        L.append(
            rf"Cubic spline & {fmt(spline['rmse'])} & "
            rf"$[{fmt(spline['rmse_ci95'][0])},\ {fmt(spline['rmse_ci95'][1])}]$ & "
            rf"{fmt(spline['mae'])} \\"
        )
        L.append(r"\bottomrule")
        L.append(r"\end{tabular}%")
        L.append(r"}")
        L.append("")

    if wings:
        L.append("% ====== Per-maturity wing exponents table ======")
        L.append(r"\newcommand{\WingTable}{%")
        L.append(r"\begin{tabular}{cccccc}")
        L.append(r"\toprule")
        L.append(r"$T$ (yr) & $\alpha_L$ & $R^2_L$ & $\alpha_R$ & $R^2_R$ & \\")
        L.append(r"\midrule")
        for w in wings:
            L.append(
                rf"{fmt(w['T'], 3)} & {fmt(w['alpha_L'], 3)} & {fmt(w['R2_L'], 3)} & "
                rf"{fmt(w['alpha_R'], 3)} & {fmt(w['R2_R'], 3)} & \\"
            )
        L.append(r"\bottomrule")
        L.append(r"\end{tabular}%")
        L.append(r"}")
        L.append("")

    OUT.write_text("\n".join(L) + "\n")
    print(f"wrote: {OUT}  ({len(L)} lines)")

    # ---- highlights.txt ----
    if cv and len(aL):
        highlights = [
            f"PINN-Dupire calibrated on a single-day cross-section of {n_clean} TSM equity options.",
            f"LOMO RMSE ${fmt(pinn['rmse'])} (PINN) vs ${fmt(ah['rmse'])} (AH), ${fmt(svi['rmse'])} (SVI).",
            "Statistically tied with Andreasen-Huge; significantly better than SVI.",
            "Local-volatility left wing follows a power-law with exponent in [1, 3].",
            "Cross-sectional characterisation of equity-options skew structure under sparsity.",
        ]
        for i, h in enumerate(highlights):
            flag = "  [OK]" if len(h) <= 85 else f"  [WARN: {len(h)} chars > 85]"
            print(f"  highlight {i+1}: {len(h):>3} chars{flag}")
        (ROOT / "highlights.txt").write_text("\n".join(highlights) + "\n")
        print(f"wrote: {ROOT / 'highlights.txt'}")


if __name__ == "__main__":
    main()
